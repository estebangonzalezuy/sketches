/**
 * Generates the two files that let shared routes know about prototypes without importing
 * them by hand. Runs automatically before dev, build, lint, typecheck and test. Both
 * outputs are git-ignored; never edit them.
 *
 *   lib/generated/registry.ts          slug → lazy import of the prototype's page.tsx (for /p/<slug>)
 *   lib/generated/public-slugs.json    slugs with "public": true (read by proxy.ts)
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { discoverPrototypes, ROOT } from "./discover";

const outDir = join(ROOT, "lib", "generated");
mkdirSync(outDir, { recursive: true });

const all = discoverPrototypes();
const pub = all.filter((p) => p.meta.public).map((p) => p.slug).sort();

const registry = `// Generated by scripts/gen-registry.ts. Do not edit.
import type { ReactNode } from "react";

type PageModule = { default: () => ReactNode | Promise<ReactNode> };

export const publicPages: Record<string, () => Promise<PageModule>> = {
${pub.map((s) => `  ${JSON.stringify(s)}: () => import("@/app/prototypes/${s}/page"),`).join("\n")}
};
`;

function write(file: string, content: string) {
  const path = join(outDir, file);
  if (existsSync(path) && readFileSync(path, "utf8") === content) return;
  writeFileSync(path, content);
}

write("registry.ts", registry);
write("public-slugs.json", JSON.stringify(pub, null, 2) + "\n");
console.log(`registry: ${all.length} prototype(s), ${pub.length} public`);
